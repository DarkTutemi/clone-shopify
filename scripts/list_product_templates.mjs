const SHOP = 'dsdujr-vn.myshopify.com';
const DRAFT_THEME_ID = '187597717689';

async function listAllTemplates() {
  const tRes = await fetch(`https://${SHOP}/admin/oauth/access_token`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ client_id: CLIENT_ID, client_secret: CLIENT_SECRET, grant_type: 'client_credentials' })
  });
  const { access_token } = await tRes.json();
  const res = await fetch(`https://${SHOP}/admin/api/2024-10/themes/${DRAFT_THEME_ID}/assets.json`, {
    headers: { 'X-Shopify-Access-Token': access_token }
  });
  const data = await res.json();
  const tpls = data.assets.filter(a => a.key.startsWith('templates/product'));
  console.log('All product templates on Draft Theme 187597717689:');
  tpls.forEach(t => console.log(' - ' + t.key));
}

listAllTemplates().catch(console.error);
